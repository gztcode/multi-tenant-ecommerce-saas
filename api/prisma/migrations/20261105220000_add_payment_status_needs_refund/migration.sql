-- 支付单新增「已收款待退款」状态（2026-11-05 审计 P0-3 / P1-3）。
--
-- ⚠️ **为什么需要它**：渠道回调确认收款时，订单可能已经不是 PENDING_PAYMENT
--    （超时关闭 / 消费者取消 / 已被另一渠道先付掉）。这时钱已经收了，
--    但它**没有结算进订单**——订单从没记过抽佣 / 货款流水，
--    也永远等不到「整单退款」把它带走 → 钱卡在平台账上。
--    这个状态就是「钱收了、待人工/商家退款」的落点。
--
-- ⚠️ **用 ADD VALUE 而不是重建枚举类型**：重建要 DROP TYPE，
--    而 payments.status 上有默认值与索引依赖，重建会连带改一堆东西。
--
-- ⚠️ **PostgreSQL 12 起允许在事务里 ADD VALUE**，但**新值不能在同一个
--    事务块里被使用**——所以本迁移只改类型定义，不动任何数据。
ALTER TYPE "PaymentStatus" ADD VALUE 'NEEDS_REFUND';
